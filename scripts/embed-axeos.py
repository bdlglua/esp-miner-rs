#!/usr/bin/env python3
"""Embed a production AxeOS build as deterministic gzip assets in ESP32 flash."""
import gzip
import hashlib
import json
import mimetypes
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def embed():
    source = ROOT / 'web/axeos/dist/axe-os'
    destination = ROOT / 'firmware/web-assets/official'
    if not (source / 'index.html').is_file():
        raise SystemExit('Build AxeOS production before embedding it.')
    provenance = json.loads((source / 'axeos-build.json').read_text())
    if provenance.get('mock') is not False:
        raise SystemExit('Refusing to embed mock data in the hardware firmware.')
    destination.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by scripts/embed-axeos.py. Do not edit.',
             'pub fn asset(path: &str) -> Option<(&\'static str, &\'static [u8])> {',
             '    match path {']
    manifest = {}
    for file in sorted(source.rglob('*')):
        if not file.is_file() or file.suffix == '.map':
            continue
        relative = file.relative_to(source).as_posix()
        data = file.read_bytes()
        compressed = gzip.compress(data, compresslevel=9, mtime=0)
        target = destination / (relative + '.gz')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(compressed)
        mime = mimetypes.guess_type(relative)[0] or 'application/octet-stream'
        if file.suffix == '.js':
            mime = 'text/javascript'
        path = '/' if relative == 'index.html' else '/' + relative
        lines.append(f'        {json.dumps(path)} => Some(({json.dumps(mime)}, include_bytes!({json.dumps(relative + ".gz")}))),')
        manifest[path] = {'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data), 'gzip': len(compressed), 'mime': mime}
    lines += ['        _ => None,', '    }', '}', '']
    # Remove stale assets only inside the generated official asset directory.
    expected = {('index.html' if p == '/' else p[1:]) + '.gz' for p in manifest}
    for file in destination.rglob('*.gz'):
        if file.relative_to(destination).as_posix() not in expected:
            file.unlink()
    (destination / 'assets.rs').write_text('\n'.join(lines))
    (destination / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'{len(manifest)} official assets embedded, {sum(x["gzip"] for x in manifest.values())} bytes in flash.')


if __name__ == '__main__':
    embed()
